#!/bin/sh

# The database secret remains outside JVM arguments and startup option logs.
if [ -f /run/secrets/datasource.password ]; then
    OE_DB_PASSWORD=$(cat /run/secrets/datasource.password) || exit 1
    [ -n "$OE_DB_PASSWORD" ] || { echo "Database password file is empty" >&2; exit 1; }
    export OE_DB_PASSWORD
fi

# Compose file secrets retain host ownership. Copy only this bootstrap secret to
# a private runtime file that Tomcat can read after privileges are dropped.
if [ -f /run/secrets/initial-admin-password ]; then
    install -d -m 750 -o 0 -g 8443 /run/openelis-secrets || exit 1
    install -m 400 -o 8443 -g 8443 /run/secrets/initial-admin-password /run/openelis-secrets/initial-admin-password || exit 1
    OE_INITIAL_ADMIN_PASSWORD_FILE=/run/openelis-secrets/initial-admin-password
    export OE_INITIAL_ADMIN_PASSWORD_FILE
fi

# The install's own key for database secrets, generated by the certs service.
# Exported rather than passed as a -D option so it never appears on a command line.
INSTALL_ENCRYPTION_KEY="/etc/openelis-global/install/encryption.key"
if [ -z "${OE_ENCRYPTION_PASSWORD:-}" ] && [ -s "$INSTALL_ENCRYPTION_KEY" ]; then
    OE_ENCRYPTION_PASSWORD=$(cat "$INSTALL_ENCRYPTION_KEY")
    export OE_ENCRYPTION_PASSWORD
fi
# The application validates its effective key. The Linux installer supplies it
# through common.properties, whose Java escape semantics must remain unchanged.

#############################################
# Permission Fix Section
#############################################

echo "Fixing OpenELIS runtime volume permissions..."

OE_LOGS="/var/lib/openelis-global/logs"
TOMCAT_LOGS="/usr/local/tomcat/logs"
LUCENE="/var/lib/lucene_index"
BRANDING="/var/lib/openelis-global/branding"
CONFIGURATION="/var/lib/openelis-global/configuration"
REPORTING="/var/lib/openelis-global/reporting"

# Create dirs if missing (safe even if mounted)
mkdir -p \
  "$OE_LOGS" \
  "$TOMCAT_LOGS" \
  "$LUCENE" \
  "$BRANDING" \
  "$CONFIGURATION" \
  "$REPORTING"

# Fix ownership → UID 8443 (tomcat_admin)
chown -R 8443:tomcat "$OE_LOGS" || true
chown -R 8443:tomcat "$TOMCAT_LOGS" || true
chown -R 8443:tomcat "$LUCENE" || true
chown -R 8443:tomcat "$BRANDING" || true
chown -R 8443:tomcat "$REPORTING" || true

# Fix permissions
chmod -R 770 "$OE_LOGS" || true
chmod -R 770 "$TOMCAT_LOGS" || true
chmod -R 770 "$LUCENE" || true
chmod -R 770 "$BRANDING" || true
chmod -R 770 "$REPORTING" || true

# The configuration tree is usually a bind mount of the deployment's git
# checkout, and the Import Catalog page writes into it. Grant the tomcat group
# instead of taking ownership, so the deployer keeps its files and git's tracked
# mode bits (chmod -R 770 would mark every CSV executable).
chgrp -R tomcat "$CONFIGURATION" || true
chmod -R g+rwX "$CONFIGURATION" || true

# Certificate uploads update the public truststore as the application user.
# Grant access to this file only; private keystores and install keys keep their modes.
TRUSTSTORE="${SSL_TRUSTSTORE_PATH:-/etc/openelis-global/truststore}"
if [ -f "$TRUSTSTORE" ]; then
    chown 8443:tomcat "$TRUSTSTORE" || exit 1
    chmod u+rw "$TRUSTSTORE" || exit 1
fi

echo "Volume permissions ready."


#############################################
# Drop privileges & start Tomcat
#############################################

echo "Starting Tomcat as tomcat_admin..."

exec su tomcat_admin -c "$CATALINA_HOME/bin/catalina.sh run"
