import { createRequire } from 'node:module';
import { mkdir, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
const require = createRequire(resolve('frontend/package.json'));
const { chromium, expect } = require('@playwright/test');
require('dotenv').config({path: '.env', quiet: true});
const evidence=resolve('.devin/artifacts/m5/program-browser');
await mkdir(evidence,{recursive:true});
const browser=await chromium.launch({headless:true});
const context=await browser.newContext({baseURL:'https://localhost:33880',ignoreHTTPSErrors:true,locale:'en',viewport:{width:1440,height:1000},recordVideo:{dir:resolve('.devin/artifacts/m5/program-browser-video')}});
context.setDefaultTimeout(30000);
const page=await context.newPage();
page.on('response',r=>{if(r.url().includes('/rest/program')) console.log('Program response',r.status(),r.url())});
const errors=[];
page.on('pageerror',error=>errors.push(error.message));
page.on('console',message=>{if(message.type()==='error')errors.push(message.text())});
try {
  await page.goto('/login',{waitUntil:'domcontentloaded'});
  await page.locator('#loginName').fill(process.env.TEST_USER || 'admin');
  await page.locator('#password').fill(process.env.TEST_PASS || 'adminADMIN!');
  await page.locator('[data-cy="loginButton"]').click();
  await expect(page).toHaveURL(/\/$/,{timeout:60000});
  await page.goto('/MasterListsPage/program',{waitUntil:'domcontentloaded'});
  await page.getByRole('button',{name:'Add Program',exact:true}).click();
  const name='V2 browser '+Date.now();
  await page.getByLabel('Program Name',{exact:true}).fill(name);
  await page.getByLabel('Programme Code',{exact:true}).fill('V2B_'+Date.now());
  await page.locator('label[for="dc-new"]').click();
  const toggle=page.getByRole('switch',{name:/Show on Microbiology case/});
  await expect(toggle).not.toBeChecked();
  await page.locator('label[for="micro-program-new"]').click();
  await expect(toggle).toBeChecked();
  await page.screenshot({path:resolve(evidence,'program-create-enabled.png'),fullPage:true});
  let save=page.waitForResponse(r=>new URL(r.url()).pathname.replace(/\/$/,'').endsWith('/rest/program')&&r.request().method()==='POST');
  await page.getByRole('button',{name:'Submit',exact:true}).click();
  console.log('Submit clicked');
  const response=await save;
  expect(response.status()).toBe(200);
  console.log('Program saved with HTTP 200');
  await page.reload();
  const tableRow=page.locator('tr').filter({has:page.getByText(name,{exact:true})});
  await tableRow.getByRole('button',{name:'Edit program'}).click();
  await expect(page.getByRole('switch',{name:/Show on Microbiology case/})).toBeChecked();
  const switchId=await page.getByRole('switch',{name:/Show on Microbiology case/}).getAttribute('id');
  await page.screenshot({path:resolve(evidence,'program-enabled-reloaded.png'),fullPage:true});
  await page.locator(`label[for="${switchId}"]`).click();
  save=page.waitForResponse(r=>new URL(r.url()).pathname.replace(/\/$/,'').endsWith('/rest/program')&&r.request().method()==='POST');
  await page.getByRole('button',{name:'Submit',exact:true}).click();
  console.log('Submit clicked');
  const disabled=await save;
  expect(disabled.status()).toBe(200);
  console.log('Program disabled with HTTP 200');
  await page.reload();
  await page.locator('tr').filter({has:page.getByText(name,{exact:true})}).getByRole('button',{name:'Edit program'}).click();
  await expect(page.getByRole('switch',{name:/Show on Microbiology case/})).not.toBeChecked();
  await page.screenshot({path:resolve(evidence,'program-disabled-reloaded.png'),fullPage:true});
  console.log('PASS: Program switch enabled, saved, reloaded, disabled and reloaded');
} finally {
  await writeFile(resolve(evidence,'console-errors.json'),JSON.stringify(errors,null,2));
  await context.close();
  await browser.close();
}
