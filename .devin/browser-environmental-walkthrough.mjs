import { createRequire } from 'node:module';
import { mkdir, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
const require = createRequire(resolve('frontend/package.json'));
const { chromium, expect } = require('@playwright/test');
require('dotenv').config({path: '.env', quiet: true});
const evidence=resolve('.devin/artifacts/m5/environmental-browser');
await mkdir(evidence,{recursive:true});
const browser=await chromium.launch({headless:true});
const context=await browser.newContext({baseURL:'https://localhost:33880',ignoreHTTPSErrors:true,locale:'en',viewport:{width:1440,height:1000},recordVideo:{dir:resolve('.devin/artifacts/m5/environmental-browser-video')}});
context.setDefaultTimeout(30000);
const page=await context.newPage();

const errors=[];
page.on('pageerror',error=>errors.push(error.message));
page.on('console',message=>{if(message.type()==='error')errors.push(message.text())});
try {
 await page.goto('/login',{waitUntil:'domcontentloaded'});
 await page.locator('#loginName').fill(process.env.TEST_USER || 'admin');
 await page.locator('#password').fill(process.env.TEST_PASS || 'adminADMIN!');
 await page.locator('[data-cy="loginButton"]').click();
 await expect(page).toHaveURL(/\/$/,{timeout:60000});
 await page.goto('/order/environmental/enter',{waitUntil:'domcontentloaded'});
 await expect(page.locator('#sampleType-0')).toBeVisible();
 await expect(page.locator('#sampleType-0 option').filter({hasText:'V2 browser water'})).toBeAttached({timeout:30000});
 await expect(page.locator('#sample-site-0 option').filter({hasText:'V2 browser site A'}).first()).toBeAttached({timeout:30000});
 console.log('Sample types:',await page.locator('#sampleType-0 option').allTextContents());
 console.log('Sites:',await page.locator('#sample-site-0 option').allTextContents());
 await page.locator('#sampleType-0').selectOption({label:'V2 browser water'});
 await page.locator('.env-manifest-toggle-btn').first().click();
 await expect(page.locator('label[for^="test-0-"]').first()).toBeAttached({timeout:30000});
 await page.locator('label[for="test-0-383"]').click();
 const siteA=await page.locator('#sample-site-0 option').filter({hasText:'V2 browser site A'}).first().getAttribute('value');
 const siteB=await page.locator('#sample-site-0 option').filter({hasText:'V2 browser site B'}).first().getAttribute('value');
 await page.locator('#sample-site-0').selectOption(siteA);
 await page.getByRole('button',{name:'Duplicate sample',exact:true}).first().click();
 await expect(page.locator('#sample-site-1')).toBeVisible();
 const preview=page.getByRole('region',{name:'What this order will open'});
 await expect(preview.getByText('Opens a case',{exact:true})).toHaveCount(1,{timeout:30000});
 await expect(preview).toContainText('V2 browser site A');
 await preview.scrollIntoViewIfNeeded();
 await page.screenshot({path:resolve(evidence,'same-site-one-case.png'),fullPage:true});
 await page.locator('#sample-site-1').selectOption(siteB);
 await expect(preview.getByText('Opens a case',{exact:true})).toHaveCount(2,{timeout:30000});
 await expect(preview).toContainText('V2 browser site B');
 await page.screenshot({path:resolve(evidence,'different-sites-two-cases.png'),fullPage:true});
 await page.locator('#sample-site-1').selectOption(siteA);
 await expect(preview.getByText('Opens a case',{exact:true})).toHaveCount(1,{timeout:30000});
 console.log('PASS: environmental site selector keeps selected tests; same sites preview one case, different sites preview two cases');
} finally {
 await writeFile(resolve(evidence,'last-page.txt'),await page.locator('body').innerText());
 await page.screenshot({path:resolve(evidence,'last-page.png'),fullPage:true});
 await writeFile(resolve(evidence,'console-errors.json'),JSON.stringify(errors,null,2));
 await context.close(); await browser.close();
}
