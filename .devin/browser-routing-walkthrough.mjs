import { createRequire } from 'node:module';
import { mkdir, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
const require = createRequire(resolve('frontend/package.json'));
const { chromium, expect } = require('@playwright/test');
require('dotenv').config({path: '.env', quiet: true});
const evidence = resolve('.devin/artifacts/m5/browser');
await mkdir(evidence, {recursive: true});
const browser = await chromium.launch({headless:true});
const context = await browser.newContext({baseURL:'https://localhost:33880',ignoreHTTPSErrors:true,locale:'en',viewport:{width:1440,height:1000},recordVideo:{dir:resolve('.devin/artifacts/m5/browser-video')}});
const page = await context.newPage();
const errors=[];
page.on('pageerror', error => errors.push(error.message));
page.on('console', message => {if(message.type()==='error') errors.push(message.text())});
try {
  await page.goto('/login', {waitUntil:'domcontentloaded'});
  await page.locator('#loginName').fill(process.env.TEST_USER || 'admin');
  await page.locator('#password').fill(process.env.TEST_PASS || 'adminADMIN!');
  await page.locator('[data-cy="loginButton"]').click();
  await expect(page).toHaveURL(/\/$/, {timeout:60000});
  await page.goto('/order/clinical/enter', {waitUntil:'domcontentloaded'});
  await expect(page.locator('#labNumber')).not.toHaveValue('', {timeout:30000});
  await page.getByTestId('order-sample-test-section').getByLabel('Sample Type *').selectOption({label:'Sputum'});
  await expect(page.locator('label[for^="test-0-"]').first()).toBeVisible({timeout:30000});
  const xpert = page.locator('label[for^="test-0-"]').filter({hasText:'Xpert MTB/RIF'});
  const testId = (await xpert.getAttribute('for')).replace('test-0-','');
  console.log('Xpert test id:', testId);
  await page.goto(`/admin/TestCatalogEditor/${testId}/basic-info`,{waitUntil:'domcontentloaded'});
  await expect(page.locator('#basic-info-opens-microbiology-case')).toBeAttached({timeout:30000});
  if (!(await page.locator('#basic-info-opens-microbiology-case').isChecked())) await page.locator('label[for="basic-info-opens-microbiology-case"]').click();
  await expect(page.getByLabel('Case role',{exact:true})).toBeVisible();
  await expect(page.getByLabel('Case role',{exact:true})).toHaveValue('DIRECT');
  await expect(page.locator('#basic-info-collected-in-sets')).toBeDisabled();
  await page.getByLabel('Case role',{exact:true}).selectOption('CULTURE');
  await expect(page.locator('#basic-info-collected-in-sets')).toBeEnabled();
  await page.screenshot({path:resolve(evidence,'catalog-culture-controls.png'),fullPage:true});
  await page.getByLabel('Case role',{exact:true}).selectOption('DIRECT');
  if (await page.getByRole('button',{name:'Save',exact:true}).isEnabled()) {
    const saveResponse = page.waitForResponse(r => r.url().includes(`/test-catalog/tests/${testId}/basic-info`) && r.request().method()==='PUT');
    await page.getByRole('button',{name:'Save',exact:true}).click();
    expect((await saveResponse).status()).toBe(200);
  }
  await page.reload();
  await expect(page.getByLabel('Case role',{exact:true})).toHaveValue('DIRECT');
  await expect(page.locator('#basic-info-opens-microbiology-case')).toBeChecked();
  await page.screenshot({path:resolve(evidence,'catalog-direct-saved.png'),fullPage:true});
  await page.goto('/order/clinical/enter',{waitUntil:'domcontentloaded'});
  await expect(page.locator('#labNumber')).not.toHaveValue('',{timeout:30000});
  await page.getByTestId('order-sample-test-section').getByLabel('Sample Type *').selectOption({label:'Sputum'});
  await page.locator('label[for^="test-0-"]').filter({hasText:'Xpert MTB/RIF'}).click();
  const preview = page.getByRole('region',{name:'What this order will open'});
  await expect(preview).toContainText('Xpert MTB/RIF',{timeout:30000});
  await expect(preview).toContainText('Opens');
  await preview.scrollIntoViewIfNeeded();
  await page.screenshot({path:resolve(evidence,'xpert-preview.png'),fullPage:true});
  const body = await page.locator('body').innerText();
  await writeFile(resolve(evidence,'xpert-preview.txt'),body);
  await page.screenshot({path:resolve(evidence,'xpert-preview-final.png'),fullPage:true});
  console.log(body);
} finally {
  await writeFile(resolve(evidence,'console-errors.json'),JSON.stringify(errors,null,2));
  await context.close();
  await browser.close();
}
